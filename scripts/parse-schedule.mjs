#!/usr/bin/env node
// Parse docs/source-schedule.md → data/seed-schedule.json + docs/import-report.md
//
//   node scripts/parse-schedule.mjs            (writes both files)
//   node scripts/parse-schedule.mjs --check    (fails if the committed files are stale)
//
// The output is a reviewable snapshot only. It never touches Firestore; see
// scripts/seed-firestore.mjs for the owner-only, dry-run-by-default import.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSchedule, ParseError } from './lib/schedule-parser.mjs';
import { validateSeed } from './lib/validate.mjs';
import { formatShort, formatLong } from '../website/js/date-utils.js';
import { SESSION_TYPES, PROFILES } from '../website/js/config.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(root, 'docs/source-schedule.md');
const SEED = resolve(root, 'data/seed-schedule.json');
const REPORT = resolve(root, 'docs/import-report.md');
const ORIGINAL_FILENAME = 'COS330_SHARED_STUDY_SCHEDULE_v3.md';

const check = process.argv.includes('--check');
const markdown = readFileSync(SOURCE, 'utf8');

// Keep importedAt stable when the source has not changed, so re-running is a no-op.
let importedAt = new Date().toISOString();
if (existsSync(SEED)) {
  try {
    const prev = JSON.parse(readFileSync(SEED, 'utf8'));
    if (prev.importedAt) importedAt = prev.importedAt;
  } catch { /* regenerate */ }
}

let result;
try {
  result = parseSchedule(markdown, { sourceFilename: ORIGINAL_FILENAME, importedAt });
} catch (err) {
  if (err instanceof ParseError) {
    console.error(`\n✖ Schedule parse failed: ${err.message}\n  Nothing was written. Fix the source or the parser, then re-run.`);
    process.exit(1);
  }
  throw err;
}
const { seed, report } = result;
const prevHash = existsSync(SEED) ? JSON.parse(readFileSync(SEED, 'utf8')).sourceHash : null;
if (prevHash && prevHash !== seed.sourceHash) seed.importedAt = new Date().toISOString();

const problems = validateSeed(seed);
if (problems.errors.length) {
  console.error('✖ Seed validation failed:\n' + problems.errors.map((e) => `  - ${e}`).join('\n'));
  process.exit(1);
}

const json = JSON.stringify(seed, null, 2) + '\n';
const md = renderReport(seed, report, problems.warnings);

if (check) {
  const stale = [];
  if (!existsSync(SEED) || readFileSync(SEED, 'utf8') !== json) stale.push('data/seed-schedule.json');
  if (!existsSync(REPORT) || readFileSync(REPORT, 'utf8') !== md) stale.push('docs/import-report.md');
  if (stale.length) {
    console.error(`✖ Out of date: ${stale.join(', ')}. Run "npm run parse" and commit the result.`);
    process.exit(1);
  }
  console.log('✔ Seed and import report are up to date with docs/source-schedule.md');
} else {
  writeFileSync(SEED, json);
  writeFileSync(REPORT, md);
  console.log(`✔ Wrote data/seed-schedule.json (${seed.topics.length} topics, ${seed.sessions.length} sessions, ${seed.discussions.length} discussions)`);
  console.log('✔ Wrote docs/import-report.md');
  for (const w of [...report.warnings, ...problems.warnings]) console.log(`  ⚠ ${w}`);
}

// ------------------------------------------------------------------ report

function esc(s) { return String(s ?? '').replace(/\|/g, '\\|'); }

function renderReport(seed, report, validationWarnings) {
  const ws = seed.workspace;
  const people = (ids) => ids.map((p) => PROFILES[p].name).join(' + ');
  const L = [];
  L.push('# Import report: COS330 shared study schedule', '');
  L.push('> Generated by `scripts/parse-schedule.mjs` from `docs/source-schedule.md`. Do not edit by hand; re-run `npm run parse`.', '');
  L.push('| Field | Value |', '|---|---|');
  L.push(`| Source file (original name) | \`${seed.sourceScheduleFilename}\` |`);
  L.push(`| Archived copy | \`${seed.sourceFile}\` (byte-identical to the supplied file) |`);
  L.push(`| Source version / revised | v${ws.sourceVersion ?? '?'} · ${ws.sourceRevised ?? 'unknown'} |`);
  L.push(`| Source SHA-256 | \`${seed.sourceHash}\` |`);
  L.push(`| Snapshot generated | ${seed.importedAt} |`);
  L.push(`| Workspace ID | \`${seed.workspaceId}\` |`);
  L.push(`| Module | ${esc(ws.moduleName)} |`);
  L.push(`| Exam | ${formatLong(ws.examDate)}, ${ws.examStart}–${ws.examEnd} · ${esc(ws.examVenue)} |`);
  L.push(`| Scope | ${esc(ws.scope)} |`);
  L.push(`| Topics (chapters) | ${seed.topics.length} |`);
  L.push(`| Sessions | ${seed.sessions.length} |`);
  L.push(`| Seeded discussion items | ${seed.discussions.length} |`);
  L.push(`| David queue items | ${ws.davidQueue.length} (${ws.queueTotalHours} h) |`);
  L.push(`| Progress records seeded | **0**. Everyone starts at "Not started" (schedule §2.8, §13) |`, '');

  L.push('## Topics', '', '| ID | Ch | Title | Group | Slides | Kyle target | David target | Joint planned | Technical examples |', '|---|---|---|---|---|---|---|---|---|');
  for (const t of seed.topics) {
    L.push(`| \`${t.id}\` | ${t.chapter} | ${esc(t.title)} | ${esc(t.group)} | ${t.slides} | ${t.targets.kyle} | ${esc(t.targets.david)} | ${t.jointPlanned.join(', ')} | ${t.examples.length} |`);
  }
  L.push('', `Excluded from scope: Chapter ${ws.excludedChapters.join(', ')} (no topic created).`, '');

  L.push('## Sessions by date', '', '| Date | ID | Type | Who | Title | Time | Topics | Tasks | Optional | Source |', '|---|---|---|---|---|---|---|---|---|---|');
  for (const s of seed.sessions) {
    L.push(`| ${formatShort(s.date)} | \`${s.id}\` | ${SESSION_TYPES[s.type].label} | ${people(s.participants)} | ${esc(s.title)} | ${esc(s.timeLabel ?? 'All day / unscheduled')} | ${s.topicIds.join(', ') || '–'} | ${s.tasks.length} | ${s.optional ? 'yes' : ''} | ${s.sourceRef.replace('docs/source-schedule.md#', '')} |`);
  }
  L.push('');

  // Days with no planned work, per person
  const dates = [...new Set(seed.sessions.map((s) => s.date))].sort();
  L.push('## Days with no planned study work', '');
  for (const p of Object.keys(PROFILES)) {
    const none = dates.filter((d) => !seed.sessions.some((s) => s.date === d && s.participants.includes(p) && ['individual', 'joint', 'practice', 'buffer'].includes(s.type) && !s.optional));
    L.push(`- **${PROFILES[p].name}:** ${none.map((d) => `${formatShort(d)} (${seed.sessions.filter((s) => s.date === d && s.participants.includes(p)).map((s) => s.title).join('; ') || 'nothing scheduled'})`).join(' · ') || 'none'}`);
  }
  L.push('');

  L.push('## Protected dates (never auto-filled by catch-up)', '');
  for (const p of ws.protectedDates) L.push(`- **${formatShort(p.date)}** (${people(p.appliesTo)}): ${p.reason}`);
  L.push('');

  L.push('## David\'s queue (§7.1)', '', '| Code | Item | Depth | Hours | Topics |', '|---|---|---|---|---|');
  for (const q of ws.davidQueue) L.push(`| ${q.code} | ${esc(q.item)} | ${q.depth} | ${q.hours} | ${q.topicIds.join(', ')} |`);
  L.push('');

  L.push('## Seeded discussion items (§14 open questions)', '');
  for (const d of seed.discussions) L.push(`- \`${d.id}\`: ${d.title} (topics: ${d.topicIds.join(', ') || '–'})`);
  L.push('');

  L.push('## Assumptions made by the importer', '');
  for (const a of report.assumptions) L.push(`- ${a}`);
  L.push('', '## Ambiguities left for Kyle and David to handle in the app', '');
  for (const a of report.ambiguities) L.push(`- ${a}`);
  L.push('', '## Warnings', '');
  const allW = [...report.warnings, ...validationWarnings];
  if (!allW.length) L.push('- None.');
  for (const w of allW) L.push(`- ${w}`);
  L.push('', '## Manual verification checklist', '');
  L.push('Check this report against `docs/source-schedule.md` line by line before seeding (spec §13.3):', '');
  L.push('- [ ] Exam date, time and venue match §1.');
  L.push('- [ ] All 12 examinable chapters are listed with the §13.1 titles; Chapter 12 is absent.');
  L.push('- [ ] Every Kyle day in §6 has one session, with the same MUST/SHOULD/COULD tasks and hours.');
  L.push('- [ ] Every David day in §7.2 has a session; Fri 13–Mon 16 are open days, and Tue 17 shows the other exam plus a light evening.');
  L.push('- [ ] J5–J7 match §9.1 dates, lengths and optional flags.');
  L.push('- [ ] Sat 14 is a study day for Kyle and Wed 18 is light; Fri 20 is practice only; Sat 21 has light revision plus the exam.');
  L.push('- [ ] No progress is pre-marked.');
  L.push('');
  return L.join('\n');
}
